ประเทศที่มีพื้นที่ใหญ่ที่สุดในทวีปอเมริกาใต้คือประเทศใด | บราซิล
ประเทศที่มีประชากรมากที่สุดในทวีปแอฟริกาคือประเทศใด | ไนจีเรีย
